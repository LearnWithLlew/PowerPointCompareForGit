#!/usr/bin/env python3
"""Writes the slide lists: experiments/artcraft/slide_list.md (committed), results/slides.csv and results/gallery.html (local images).

usage: write_lists.py ROOT OUT_MD
"""
import collections, csv, html, json, sys
from pathlib import Path

root, out_md = Path(sys.argv[1]).resolve(), Path(sys.argv[2])
results = root / "results"
read = lambda name: [json.loads(line) for line in (results / name).read_text().splitlines()]
slides, features = read("slides.jsonl"), {(f["deck"], f["slide"]): f for f in read("features.jsonl")}
causes = collections.defaultdict(list)
for name, entries in json.loads((results / "cause_tags.json").read_text()).items():
    for deck, slide in entries:
        causes[(deck, slide)].append(name)
ORDER = ["major", "moderate", "minor", "identical"]


def ranges(numbers):
    numbers, parts, start = sorted(numbers), [], None
    for i, n in enumerate(numbers):
        start = n if start is None else start
        if i + 1 == len(numbers) or numbers[i + 1] != n + 1:
            parts.append(str(n) if start == n else f"{start}-{n}")
            start = None
    return ", ".join(parts)


by_deck = collections.defaultdict(list)
for s in slides:
    by_deck[s["deck"]].append(s)
totals = collections.Counter(s["severity"] for s in slides)
lines = ["# Slides that differ between LibreOffice and DeckCraft", "",
         f"Generated by `write_lists.py`. {len(by_deck)} decks, {len(slides)} slides: " + ", ".join(f"{totals[k]} {k}" for k in ORDER) + ".", "",
         "- **major**: one slide is blank, or one solid region of at least 3% of the slide changed.",
         "- **moderate**: a solid region of 1-3% changed, or at least 5% of the slide's 16px blocks did.",
         "- **minor**: only small scattered changes, usually text anti-aliasing or a slightly different font.",
         "- **identical**: every pixel matches.", "",
         "These are scores, not verdicts. A large title in another font scores major. See `REPORT.md` for what the differences are.", ""]
for deck, rows in sorted(by_deck.items(), key=lambda kv: (-sum(r["severity"] == "major" for r in kv[1]), kv[0])):
    lines += [f"## {deck}", "", f"{len(rows)} slides.", ""]
    for severity in ORDER:
        numbers = [r["slide"] for r in rows if r["severity"] == severity]
        if numbers:
            lines.append(f"- {severity} ({len(numbers)}): {ranges(numbers)}")
    tagged = collections.defaultdict(list)
    for r in rows:
        for cause in causes[(deck, r["slide"])]:
            tagged[cause].append(r["slide"])
    for cause, numbers in sorted(tagged.items()):
        lines.append(f"- contains {cause}: {ranges(numbers)}")
    lines.append("")
out_md.write_text("\n".join(lines))

with (results / "slides.csv").open("w", newline="") as file:
    writer = csv.writer(file)
    writer.writerow(["deck", "slide", "severity", "pixel_pct", "coarse_pct", "largest_region_pct", "hidden", "features", "causes", "image"])
    for s in slides:
        f = features[(s["deck"], s["slide"])]
        writer.writerow([s["deck"], s["slide"], s["severity"], s["pixel_pct"], s["coarse_pct"], s["largest_region_pct"], f["hidden"], " ".join(f["features"]), " ".join(causes[(s["deck"], s["slide"])]), s.get("image", "")])

page = ["<!doctype html><meta charset=utf-8><title>LibreOffice vs DeckCraft</title><style>body{font:14px system-ui;margin:16px}img{width:100%;max-width:1500px;display:block}figure{margin:0 0 18px}details{margin:6px 0}summary{cursor:pointer;font-weight:600}</style>",
        "<h1>LibreOffice vs DeckCraft</h1><p>Each image: LibreOffice | DeckCraft | changed pixels.</p>"]
for deck, rows in sorted(by_deck.items(), key=lambda kv: (-sum(r["severity"] == "major" for r in kv[1]), kv[0])):
    count = collections.Counter(r["severity"] for r in rows)
    page.append(f"<h2>{html.escape(deck)}</h2><p>" + ", ".join(f"{count[k]} {k}" for k in ORDER if count[k]) + "</p>")
    for severity in ORDER[:3]:
        chosen = sorted((r for r in rows if r["severity"] == severity), key=lambda r: r["slide"])
        if chosen:
            page.append(f"<details{' open' if severity == 'major' else ''}><summary>{severity} ({len(chosen)})</summary>")
            for r in chosen:
                note = " ".join(causes[(deck, r["slide"])])
                page.append(f"<figure><figcaption>Slide {r['slide']} region {r['largest_region_pct']}% {html.escape(note)}</figcaption><img loading=lazy src='{html.escape(r['image'])}'></figure>")
            page.append("</details>")
(results / "gallery.html").write_text("\n".join(page))
